/**
 * Writes docs/audit/content-report.md: one document a reviewer can read to audit
 * every lesson, quiz item, breed fact, source and pinned photo.
 *
 *   npm run audit
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildContent, checkIntegrity } from "../src/content/parse";
import type { Breed, Lesson, QuizItem } from "../src/content/schema";
import { readAllContent, ROOT } from "./lib/content";

const { curriculum, breeds, lessons, errors } = readAllContent();
if (!curriculum || errors.length) {
  console.error("Content has errors; run `npm run validate` first.\n" + errors.join("\n"));
  process.exit(1);
}
const problems = checkIntegrity(curriculum, breeds, lessons);
const content = buildContent(curriculum, breeds, lessons);
const breedName = (slug: string) => content.breeds.get(slug)?.name ?? `UNKNOWN(${slug})`;
const status = (by: string, on: string) => (by ? `Reviewed by ${by}${on ? ` on ${on}` : ""}` : "**NOT REVIEWED**");
const esc = (s: string) => s.replaceAll("|", "\\|");

function quizLine(item: QuizItem, i: number): string {
  switch (item.type) {
    case "identify":
      return `${i + 1}. **Identify** (photo -> name): ${breedName(item.breed)}${
        item.image ? ` using [pinned photo](${item.image})` : " using a random pinned photo"
      }${item.distractors ? `; wrong choices: ${item.distractors.map(breedName).join(", ")}` : "; wrong choices chosen automatically from look-alikes and same group"}`;
    case "find":
      return `${i + 1}. **Find** (name -> photo): ${breedName(item.breed)}${
        item.distractors ? `; wrong choices: ${item.distractors.map(breedName).join(", ")}` : "; wrong choices chosen automatically"
      }`;
    case "question":
      return [
        `${i + 1}. **Question:** ${item.prompt}`,
        ...item.choices.map((c) => `   - ${c === item.answer ? `**${c}** (correct)` : c}`),
        ...(item.explanation ? [`   - _Explanation:_ ${item.explanation}`] : []),
      ].join("\n");
  }
}

function lessonSection(lesson: Lesson): string {
  const lines = [
    `### ${lesson.title}`,
    "",
    `- **ID:** \`${lesson.id}\``,
    `- **File:** \`${lesson.file}\``,
    `- **Review status:** ${status(lesson.reviewedBy, lesson.reviewedOn)}`,
    `- **Prerequisites:** ${lesson.prerequisites.length ? lesson.prerequisites.map((p) => `\`${p}\``).join(", ") : "none"}`,
    `- **Pass mark:** ${Math.round(lesson.passMark * 100)}%`,
    `- **Breeds taught:** ${lesson.breeds.length ? lesson.breeds.map(breedName).join(", ") : "none"}`,
    "",
    "**Objectives**",
    "",
    ...lesson.objectives.map((o) => `- ${o}`),
    "",
  ];
  if (lesson.compare.length) {
    lines.push("**Comparisons:** " + lesson.compare.map(([a, b]) => `${breedName(a)} vs ${breedName(b)}`).join("; "), "");
  }
  if (lesson.images.length) {
    lines.push("**Lesson photos**", "", "| Breed | Caption | Photo |", "| --- | --- | --- |");
    for (const img of lesson.images)
      lines.push(`| ${breedName(img.breed)} | ${esc(img.caption)} | [view](${img.url}) |`);
    lines.push("");
  }
  if (lesson.sources.length) {
    lines.push("**Sources**", "", ...lesson.sources.map((s) => `- [${s.title}](${s.url})`), "");
  }
  lines.push(`**Quiz (${lesson.quiz.length} items)**`, "", ...lesson.quiz.map(quizLine), "");
  lines.push("<details><summary>Lesson text</summary>", "", lesson.body, "", "</details>", "");
  return lines.join("\n");
}

function breedSection(breed: Breed): string {
  const sources = new Map(breed.sources.map((s) => [s.id, s]));
  return [
    `### ${breed.name}`,
    "",
    `- **Slug:** \`${breed.slug}\` | **Dog CEO path:** \`${breed.dogCeoPath}\` | **AKC group:** ${breed.group} | **Size:** ${breed.size} | **Origin:** ${breed.origin}`,
    `- **Review status:** ${status(breed.reviewedBy, breed.reviewedOn)}`,
    `- **Look-alikes:** ${breed.lookAlikes.length ? breed.lookAlikes.map(breedName).join(", ") : "none"}`,
    `- **Used in lessons:** ${
      lessons
        .filter((l) => l.breeds.includes(breed.slug))
        .map((l) => `\`${l.id}\``)
        .join(", ") || "none"
    }`,
    "",
    "| Identifying trait | Source |",
    "| --- | --- |",
    ...breed.traits.map((t) => {
      const s = sources.get(t.source);
      return `| ${esc(t.text)} | ${s ? `[${esc(s.title)}](${s.url})` : `MISSING (${t.source})`} |`;
    }),
    "",
    "| # | Pinned photo | Reviewed | Note |",
    "| --- | --- | --- | --- |",
    ...breed.images.map((img, i) => `| ${i + 1} | [${img.url.split("/").pop()}](${img.url}) | ${img.reviewed ? "yes" : "**no**"} | ${esc(img.note)} |`),
    "",
  ].join("\n");
}

const allImages = breeds.flatMap((b) => b.images);
const out = [
  `# ${curriculum.title} - Content Audit Report`,
  "",
  "_Generated by `npm run audit` from the files in `content/`. Do not edit by hand; edit the content files and regenerate._",
  "",
  "## Summary",
  "",
  `- Units: ${curriculum.units.length}`,
  `- Lessons: ${lessons.length} (${lessons.filter((l) => l.reviewedBy).length} reviewed)`,
  `- Breeds: ${breeds.length} (${breeds.filter((b) => b.reviewedBy).length} reviewed)`,
  `- Pinned photos: ${allImages.length} (${allImages.filter((i) => i.reviewed).length} reviewed)`,
  `- Integrity problems: ${problems.length ? problems.length : "none"}`,
  ...problems.map((p) => `  - ${p}`),
  "",
  "## How to audit",
  "",
  "1. For each lesson, check that the text and quiz answers are accurate and match the objectives.",
  "2. For each breed, check every trait against its cited source.",
  "3. Open each pinned photo and confirm it clearly shows that breed. Set `reviewed: true` in the breed file, or delete the photo and run `npm run pin-images` to pick a replacement.",
  "4. Fill in `reviewedBy` and `reviewedOn` in the lesson or breed file, then rerun `npm run validate` and `npm run audit`.",
  "",
  "Photos come from the [Dog CEO API](https://dog.ceo/dog-api/), which mostly uses the [Stanford Dogs Dataset](http://vision.stanford.edu/aditya86/ImageNetDogs/) (filenames like `n02085620_123.jpg`).",
  "",
  "## Curriculum",
  "",
  ...curriculum.units.flatMap((u) => [
    `### ${u.title}`,
    "",
    u.description,
    "",
    ...u.lessons.map((id, i) => `${i + 1}. ${content.lessons.get(id)?.title ?? id} (\`${id}\`)`),
    "",
  ]),
  "## Lessons",
  "",
  ...content.lessonOrder.map((id) => lessonSection(content.lessons.get(id)!)),
  "## Breeds",
  "",
  ...[...breeds].sort((a, b) => a.name.localeCompare(b.name)).map(breedSection),
].join("\n");

const dir = join(ROOT, "docs", "audit");
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, "content-report.md"), out);
console.log(`Wrote docs/audit/content-report.md (${lessons.length} lessons, ${breeds.length} breeds).`);
